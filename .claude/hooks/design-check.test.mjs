import assert from "node:assert/strict";
import { test } from "node:test";
import { checkDesignContent, evaluateDesignToolPayload } from "./design-check.mjs";

test("rejects raw hex color outside token owners", () => {
  const findings = checkDesignContent(
    "web/apps/console/src/styles.css",
    ".panel { color: #ff00aa; }",
  );
  assert.ok(findings.some((f) => f.includes("raw #hex colors")));
});

test("allows raw hex color inside web/packages/tokens and desktop theme.rs", () => {
  assert.deepEqual(
    checkDesignContent("web/packages/tokens/src/tokens.css", ":root { --bg-canvas: #FFFFFF; }"),
    [],
  );
  assert.deepEqual(
    checkDesignContent(
      "desktop/grdr-desktop/src/theme.rs",
      "const CANVAS_LIGHT: &str = \"#FFFFFF\";",
    ),
    [],
  );
});

test("rejects indigo/violet defaults, emojis, left border stripes, CDNs, and buzzwords", () => {
  const sample = `
    .card { border-inline-start: 3px solid var(--tone-allow); box-shadow: 0 0 20px rgba(139,92,246,0.5); }
    const title = "World-class posture monitor";
    const cdn = "https://fonts.googleapis.com/css2?family=Inter";
    const icon = "🚀";
  `;
  const findings = checkDesignContent("web/apps/console/src/pages/HomePage.tsx", sample);
  assert.ok(findings.length >= 4, findings.join("\n"));
});

test("rejects direct @astryxdesign or @ui-sdk import outside web/packages/ui", () => {
  const findings = checkDesignContent(
    "web/packages/kit/src/ModeControl.tsx",
    'import { SegmentedControl } from "@ui-sdk/react/segmented-control";',
  );
  assert.ok(findings.some((f) => f.includes("ARCH-101..104")));
  assert.deepEqual(
    checkDesignContent(
      "web/packages/ui/src/primitives.tsx",
      'import { SegmentedControl } from "@ui-sdk/react/segmented-control";',
    ),
    [],
  );
});

test("evaluates both Antigravity and Claude Code write payloads", () => {
  const agyDeny = evaluateDesignToolPayload(
    {
      toolCall: {
        name: "write_file",
        args: {
          Path: "D:/repo/web/apps/console/src/Foo.tsx",
          Content: "export const x = 'Built for seamless posture tracking';",
        },
      },
    },
    "D:/repo",
  );
  assert.ok(agyDeny.length >= 2);

  const claudeDeny = evaluateDesignToolPayload(
    {
      tool_name: "Edit",
      tool_input: {
        file_path: "D:/repo/web/apps/console/src/Foo.css",
        new_string: ".box { border-left: 4px solid red; font-family: 'Space Grotesk'; }",
      },
    },
    "D:/repo",
  );
  assert.ok(claudeDeny.length >= 2);
});

test("rejects hand-drawn SVG markup and standalone .svg assets while allowing generated icon output", () => {
  const webFindings = checkDesignContent(
    "web/apps/console/src/pages/HomePage.tsx",
    'export function Ring() { return <svg width="64" height="64"><circle cx="32" cy="32" r="24" /></svg>; }',
  );
  assert.ok(webFindings.some((f) => f.includes("hand-drawn <svg>")));

  const rustFindings = checkDesignContent(
    "desktop/grdr-desktop/src/kit.rs",
    'const BAD: &str = r#"<path d="M0 0 L10 10"/>"#;',
  );
  assert.ok(rustFindings.some((f) => f.includes("hand-drawn <svg>")));

  const brandFindings = checkDesignContent("interface/brand/custom.svg", "<svg></svg>");
  assert.ok(brandFindings.some((f) => f.includes("hand-authored .svg files are forbidden")));

  assert.deepEqual(
    checkDesignContent(
      "desktop/grdr-desktop/src/icons.rs",
      '// @generated by scripts/gen-desktop-icons.mjs\npub static X: &str = r#"<path d="M12 2v20"/>"#;',
    ),
    [],
  );
});

test("rejects raw HTML form controls and internal jargon in customer-facing UI paths", () => {
  const selectFindings = checkDesignContent(
    "web/apps/console/src/pages/TesterPage.tsx",
    'export function Pick() { return <select><option>a</option></select>; }',
  );
  assert.ok(selectFindings.some((f) => f.includes("Astryx primitives")));

  assert.deepEqual(
    checkDesignContent(
      "web/apps/console/src/App.tsx",
      'import { Dialog } from "@grdr/ui"; export function Modal() { return <Dialog isOpen={false} onOpenChange={() => {}} />; }',
    ),
    [],
  );

  const uiWrapperAllowed = checkDesignContent(
    "web/packages/ui/src/components.tsx",
    "export function Wrapper() { return <input type='hidden' />; }",
  );
  assert.deepEqual(uiWrapperAllowed, []);

  const jargonFindings = checkDesignContent(
    "web/apps/console/src/pages/InventoryPage.tsx",
    'export const txt = "Boundary (AL3/AL4) with G1/G2 grants";',
  );
  assert.ok(jargonFindings.some((f) => f.includes("plain language")));
});

test("rejects em dashes, en dashes, semicolon prose, and AI writing tells while allowing domain terms", () => {
  const dashFindings = checkDesignContent(
    "crates/grdr-ui-model/src/lib.rs",
    'pub const MSG: &str = "Local proxy — verified";',
  );
  assert.ok(dashFindings.some((f) => f.includes("em dashes and en dashes")));

  const enDashFindings = checkDesignContent(
    "desktop/grdr-desktop/src/screens/rules.rs",
    'const RANGE: &str = "Steps 1–3";',
  );
  assert.ok(enDashFindings.some((f) => f.includes("em dashes and en dashes")));

  const semiQuoted = checkDesignContent(
    "web/packages/i18n/src/index.ts",
    'export const A = "Discovered on device; no hook active yet";',
  );
  assert.ok(semiQuoted.some((f) => f.includes("semicolon-joined sentences")));

  const semiJsx = checkDesignContent(
    "web/apps/console/src/pages/HomePage.tsx",
    "export function BannerText() { return <p>One action waits; click below to review.</p>; }",
  );
  assert.ok(semiJsx.some((f) => f.includes("semicolon-joined sentences")));

  const dataUriAllowed = checkDesignContent(
    "web/apps/console/src/pages/HomePage.tsx",
    'export const IMG = "data:image/png; base64,AAAA";',
  );
  assert.deepEqual(dataUriAllowed, []);

  for (const phrase of [
    "Delve into agent logs",
    "Protect endpoints effortlessly",
    "Not just fast, but reliable",
    "Not just security but clarity",
    "Elevate your fleet defense",
  ]) {
    const tellFindings = checkDesignContent(
      "web/packages/kit/src/Hero.tsx",
      `export const copy = ${JSON.stringify(phrase)};`,
    );
    assert.ok(tellFindings.some((f) => f.includes("AI writing tells")), phrase);
  }

  assert.deepEqual(
    checkDesignContent(
      "web/apps/console/src/pages/CoveragePage.tsx",
      'export const HEAD = "Agent harness"; export const VAL = "elevate";',
    ),
    [],
  );
});

test("rejects plaintext device/agent/session/rule JSX text while allowing EntityLink", () => {
  const inlinePlain = checkDesignContent(
    "web/apps/console/src/pages/HomePage.tsx",
    "export function Host() { return <strong>{device.hostname}</strong>; }",
  );
  assert.ok(inlinePlain.some((f) => f.includes("EntityLink")));

  const blockPlain = checkDesignContent(
    "web/apps/console/src/pages/RespondPage.tsx",
    "export function Cell({ inc }: any) {\n  return (\n    <td>\n      {inc.session_id}\n    </td>\n  );\n}",
  );
  assert.ok(blockPlain.some((f) => f.includes("EntityLink")));

  assert.deepEqual(
    checkDesignContent(
      "web/apps/console/src/pages/HomePage.tsx",
      'export function HostLink({ device, onOpen }: any) {\n  return <EntityLink kind="device" id={device.id} label={device.hostname} onSelect={onOpen} />;\n}',
    ),
    [],
  );
});
