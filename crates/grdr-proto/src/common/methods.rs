#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MethodDescriptor {
    pub service: &'static str,
    pub method: &'static str,
    pub path: &'static str,
    pub idempotency: IdempotencyLevel,
    pub scope: &'static str,
    pub audit: AuditClass,
    pub rate_class: RateClass,
    pub confirm: ConfirmClass,
    pub mcp_exposed: bool,
    pub collection: Option<CollectionKind>,
}

macro_rules! rpc {
    ($svc:expr, $name:literal, $path:literal, $idem:expr, $scope:literal, $audit:expr, $rate:expr, $confirm:expr, $mcp:expr, $col:expr) => {
        MethodDescriptor {
            service: $svc,
            method: $name,
            path: $path,
            idempotency: $idem,
            scope: $scope,
            audit: $audit,
            rate_class: $rate,
            confirm: $confirm,
            mcp_exposed: $mcp,
            collection: $col,
        }
    };
}

