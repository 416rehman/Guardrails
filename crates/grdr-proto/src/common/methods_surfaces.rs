macro_rules! ext_rpc {
    ($svc:expr, $name:literal, $path:literal, $idem:expr, $scope:literal, $audit:expr, $rate:expr, $confirm:expr, $mcp:expr, $col:expr) => {
        MethodDescriptor {
            service: $svc,
            method: $name,
            path: $path,
            idempotency: $idem,
            scope: $scope,
            audit: $audit,
            rate_class: $rate,
            confirm: $confirm,
            mcp_exposed: $mcp,
            collection: $col,
        }
    };
}

