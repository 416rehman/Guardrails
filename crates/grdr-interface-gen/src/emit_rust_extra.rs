/// Renders `crates/grdr-messages/src/generated.rs` from contract manifests.
#[must_use]
pub fn render_grdr_messages(bundle: &InterfaceBundle) -> String {
    let mut out = String::new();
    out.push_str(concat!(
        "// SPDX-",
        "License-Identifier: Apache-2.0\n",
        "// SPDX-FileCopyrightText: The Guardrails ADR Authors\n",
        "// @generated by grdr-interface-gen from contracts/interface/. Do not edit by hand.\n\n",
    ));
    out.push_str(
        "use grdr_strings::{Locale, PRESENTATIONS, english_by_id, format_for_locale};\n\n",
    );
    let _ = writeln!(
        out,
        "pub const GENERATED_BRAND_NAME: &str = {};\n",
        rust_str(&bundle.vocabulary.brand_name)
    );
    out.push_str("#[derive(Clone, Debug, PartialEq, Eq)]\n");
    out.push_str("pub struct PresentedValue {\n");
    out.push_str("    pub label: String,\n");
    out.push_str("    pub description: Option<String>,\n");
    out.push_str("    pub icon_key: &'static str,\n");
    out.push_str("    pub tone: &'static str,\n");
    out.push_str("}\n\n");

    let mut needed_keys = BTreeSet::new();
    for entry in &bundle.presentations {
        needed_keys.insert(entry.label.as_str());
        if let Some(desc) = &entry.description {
            needed_keys.insert(desc.as_str());
        }
    }
    out.push_str("fn translated_presentation_text(locale: Locale, token_id: &str) -> Option<&'static str> {\n");
    out.push_str("    match locale {\n");
    for tr in &bundle.translations {
        if let Some(loc) = bundle.locales.iter().find(|l| l.tag == tr.locale_tag) {
            let matching: Vec<(&String, &String)> = tr
                .entries
                .iter()
                .filter(|(k, _)| needed_keys.contains(k.as_str()))
                .collect();
            if matching.is_empty() {
                continue;
            }
            let _ = writeln!(
                out,
                "        Locale::{} => match token_id {{",
                loc.rust_variant
            );
            for (k, v) in matching {
                write_match_some_arm(&mut out, k, v, "            ");
            }
            out.push_str("            _ => None,\n        },\n");
        }
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    out.push_str("/// Looks up a presentation-registry entry by enum name and serialized value.\n");
    out.push_str("#[must_use]\n");
    out.push_str(
        "pub fn present_enum(enum_name: &str, value: &str, locale: Locale) -> Option<PresentedValue> {\n",
    );
    out.push_str("    let entry = PRESENTATIONS\n");
    out.push_str("        .iter()\n");
    out.push_str("        .find(|item| item.enum_name == enum_name && item.value == value)?;\n");
    out.push_str("    let label = match translated_presentation_text(locale, entry.label_key) {\n");
    out.push_str("        Some(text) => text.to_owned(),\n");
    out.push_str("        None => format_for_locale(locale, english_by_id(entry.label_key)?),\n");
    out.push_str("    };\n");
    out.push_str("    let description = entry.description_key.and_then(|key| {\n");
    out.push_str("        translated_presentation_text(locale, key)\n");
    out.push_str("            .map(str::to_owned)\n");
    out.push_str(
        "            .or_else(|| english_by_id(key).map(|base| format_for_locale(locale, base)))\n",
    );
    out.push_str("    });\n");
    out.push_str("    Some(PresentedValue {\n");
    out.push_str("        label,\n");
    out.push_str("        description,\n");
    out.push_str("        icon_key: entry.icon_key,\n");
    out.push_str("        tone: entry.tone,\n");
    out.push_str("    })\n");
    out.push_str("}\n");

    out
}

