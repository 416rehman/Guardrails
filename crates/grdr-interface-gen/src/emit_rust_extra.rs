fn parse_mf2_variant_line(line: &str) -> Option<(&str, &str)> {
    let trimmed = line.trim();
    let open_idx = trimmed.find("{{")?;
    let prefix = trimmed.get(..open_idx)?.trim();
    let rest = trimmed.get(open_idx..)?;
    let body = rest.strip_prefix("{{")?.strip_suffix("}}")?;
    if prefix.is_empty() {
        None
    } else {
        Some((prefix, body))
    }
}

/// Evaluates MessageFormat 2 `.input`/`.match` templates and `{var}` placeholders.
#[must_use]
pub fn resolve_mf2_template(template: &str, count: Option<i64>, locale: Locale) -> String {
    let trimmed = template.trim();
    let mut selected = trimmed;
    let mut count_var = "count";
    let mut lines = trimmed.lines();
    if let (Some(line0), Some(line1)) = (lines.next(), lines.next()) {
        let t0 = line0.trim();
        let t1 = line1.trim();
        if t0.starts_with(".input ") && t1.starts_with(".match $") {
            if let Some(var) = t1.strip_prefix(".match $")
                && let Some(first_word) = var.split_whitespace().next()
            {
                count_var = first_word;
            }
            let exact = count.map(|n| n.to_string());
            let category = count.map(|n| plural_category(locale, n));
            let mut matched: Option<&str> = None;
            let mut wildcard: Option<&str> = None;
            for line in lines {
                if let Some((selector, variant_body)) = parse_mf2_variant_line(line) {
                    if let (Some(ex), Some(cat)) = (exact.as_deref(), category)
                        && (selector == ex || selector == cat)
                    {
                        matched = Some(variant_body);
                        break;
                    }
                    if selector == "*" && wildcard.is_none() {
                        wildcard = Some(variant_body);
                    }
                }
            }
            if let Some(chosen) = matched.or(wildcard) {
                selected = chosen;
            }
        }
    }

    let mut out = String::with_capacity(selected.len());
    let mut rest = selected;
    while let Some(start) = rest.find("{$") {
        if let Some(prefix) = rest.get(..start) {
            out.push_str(prefix);
        }
        let Some(after_open) = rest.get(start..) else {
            break;
        };
        let Some(end) = after_open.find('}') else {
            out.push_str(after_open);
            rest = "";
            break;
        };
        let var_name = after_open
            .get(2..end)
            .and_then(|tok| tok.split_whitespace().next())
            .unwrap_or_default();
        if let Some(n) = count
            && (var_name == count_var || var_name == "count")
        {
            out.push_str(&n.to_string());
        } else {
            out.push('{');
            out.push_str(var_name);
            out.push('}');
        }
        rest = end
            .checked_add(1)
            .and_then(|idx| after_open.get(idx..))
            .unwrap_or_default();
    }
    out.push_str(rest);
    out
}

/// Renders a language token cleanly for the requested locale.
#[must_use]
pub fn lookup(locale: Locale, key: MessageKey) -> String {
    if let Some(tr) = translated_by_id(locale, key.token_id()) {
        return resolve_mf2_template(tr, None, locale);
    }
    let resolved = resolve_mf2_template(key.english(), None, locale);
    format_for_locale(locale, &resolved)
}

