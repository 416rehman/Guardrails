pub fn render_grdr_strings(bundle: &InterfaceBundle) -> String {
    let mut out = String::new();
    out.push_str(concat!(
        "// SPDX-",
        "License-Identifier: Apache-2.0\n",
        "// SPDX-FileCopyrightText: The Guardrails ADR Authors\n",
        "// @generated by grdr-interface-gen from contracts/interface/. Do not edit by hand.\n\n",
    ));
    out.push_str("use serde::{Deserialize, Serialize};\n\n");

    write_locale_enum(&mut out, bundle);
    let rust_messages = collect_rust_messages(bundle);
    write_message_key_enum(&mut out, &rust_messages);
    write_registry_types(&mut out);
    write_brand_and_registries(&mut out, bundle);
    write_locale_impl(&mut out, bundle);
    write_message_key_impl(&mut out, &rust_messages);
    write_lookup_fns(&mut out, bundle);
    out
}

/// Formats a Rust double-quoted string literal without fallback or invalid escapes.
#[must_use]
pub fn rust_str(value: &str) -> String {
    let mut out = String::with_capacity(value.len().saturating_add(2));
    out.push('"');
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn write_locale_enum(out: &mut String, bundle: &InterfaceBundle) {
    out.push_str(
        "/// Locale identifier supported by Guardrails desktop, CLI, and pseudo-locale CI checks (D-69).\n",
    );
    out.push_str(
        "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]\n",
    );
    out.push_str("#[serde(rename_all = \"kebab-case\")]\n");
    out.push_str("pub enum Locale {\n");
    for (idx, loc) in bundle.locales.iter().enumerate() {
        if idx == 0 {
            out.push_str("    #[default]\n");
        }
        let _ = writeln!(out, "    {},", loc.rust_variant);
    }
    out.push_str("}\n\n");
}

fn write_message_key_enum(out: &mut String, rust_messages: &[&MessageSpec]) {
    out.push_str(
        "/// Typed language-token identifiers used by desktop, CLI, tray, and `grdr-approve`.\n",
    );
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]\n");
    out.push_str("#[serde(rename_all = \"snake_case\")]\n");
    out.push_str("pub enum MessageKey {\n");
    for msg in rust_messages {
        if let Some(variant) = &msg.rust_variant {
            let _ = writeln!(out, "    {variant},");
        }
    }
    out.push_str("}\n\n");
}

fn write_registry_types(out: &mut String) {
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("pub struct IconRegistryEntry {\n");
    out.push_str("    pub key: &'static str,\n");
    out.push_str("    pub lucide: &'static str,\n");
    out.push_str("    pub mirror: bool,\n");
    out.push_str("}\n\n");

    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("pub struct PresentationRegistryEntry {\n");
    out.push_str("    pub enum_name: &'static str,\n");
    out.push_str("    pub value: &'static str,\n");
    out.push_str("    pub label_key: &'static str,\n");
    out.push_str("    pub description_key: Option<&'static str>,\n");
    out.push_str("    pub icon_key: &'static str,\n");
    out.push_str("    pub tone: &'static str,\n");
    out.push_str("}\n\n");
}

fn write_brand_and_registries(out: &mut String, bundle: &InterfaceBundle) {
    let _ = writeln!(
        out,
        "pub const BRAND_NAME: &str = {};",
        rust_str(&bundle.vocabulary.brand_name)
    );
    let _ = writeln!(
        out,
        "pub const BRAND_SHORT_NAME: &str = {};\n",
        rust_str(&bundle.vocabulary.brand_short_name)
    );

    out.push_str("pub const ICONS: &[IconRegistryEntry] = &[\n");
    for icon in &bundle.icons {
        out.push_str("    IconRegistryEntry {\n");
        let _ = writeln!(out, "        key: {},", rust_str(&icon.key));
        let _ = writeln!(out, "        lucide: {},", rust_str(&icon.lucide));
        let _ = writeln!(out, "        mirror: {},", icon.mirror);
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    out.push_str("pub const PRESENTATIONS: &[PresentationRegistryEntry] = &[\n");
    for entry in &bundle.presentations {
        let desc = match &entry.description {
            Some(d) => format!("Some({})", rust_str(d)),
            None => "None".to_owned(),
        };
        out.push_str("    PresentationRegistryEntry {\n");
        let _ = writeln!(out, "        enum_name: {},", rust_str(&entry.enum_name));
        let _ = writeln!(out, "        value: {},", rust_str(&entry.value));
        let _ = writeln!(out, "        label_key: {},", rust_str(&entry.label));
        let _ = writeln!(out, "        description_key: {desc},");
        let _ = writeln!(out, "        icon_key: {},", rust_str(&entry.icon));
        let _ = writeln!(out, "        tone: {},", rust_str(&entry.tone));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");
}

fn write_locale_impl(out: &mut String, bundle: &InterfaceBundle) {
    out.push_str("impl Locale {\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn code(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for loc in &bundle.locales {
        let _ = writeln!(
            out,
            "            Self::{} => {},",
            loc.rust_variant,
            rust_str(&loc.tag)
        );
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn direction(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for loc in &bundle.locales {
        let _ = writeln!(
            out,
            "            Self::{} => {},",
            loc.rust_variant,
            rust_str(&loc.direction)
        );
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn script(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for loc in &bundle.locales {
        let _ = writeln!(
            out,
            "            Self::{} => {},",
            loc.rust_variant,
            rust_str(&loc.script)
        );
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn parse_tag(raw: &str) -> Option<Self> {\n");
    out.push_str("        match raw.trim().to_ascii_lowercase().as_str() {\n");
    for loc in &bundle.locales {
        if loc.aliases.is_empty() {
            let _ = writeln!(
                out,
                "            {} => Some(Self::{}),",
                rust_str(&loc.tag.to_ascii_lowercase()),
                loc.rust_variant
            );
        } else {
            let pats: Vec<String> = loc.aliases.iter().map(|a| rust_str(a)).collect();
            let arm = format!(
                "            {} => Some(Self::{}),",
                pats.join(" | "),
                loc.rust_variant
            );
            if arm.len() <= 100 {
                let _ = writeln!(out, "{arm}");
            } else {
                let _ = writeln!(out, "            {} => {{", pats.join(" | "));
                let _ = writeln!(out, "                Some(Self::{})", loc.rust_variant);
                out.push_str("            }\n");
            }
        }
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n\n");
}

fn write_message_key_impl(out: &mut String, rust_messages: &[&MessageSpec]) {
    out.push_str("impl MessageKey {\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn token_id(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for msg in rust_messages {
        if let Some(variant) = &msg.rust_variant {
            let _ = writeln!(out, "            Self::{variant} => {},", rust_str(&msg.id));
        }
    }
    out.push_str("        }\n    }\n\n");

    out.push_str("    #[must_use]\n");
    out.push_str("    pub fn english(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for msg in rust_messages {
        if let Some(variant) = &msg.rust_variant {
            let _ = writeln!(
                out,
                "            Self::{variant} => {},",
                rust_str(&msg.msg)
            );
        }
    }
    out.push_str("        }\n    }\n}\n\n");
}

fn write_lookup_fns(out: &mut String, bundle: &InterfaceBundle) {
    out.push_str("/// Looks up any generated language token by string identifier.\n");
    out.push_str("#[must_use]\n");
    out.push_str("pub fn english_by_id(token_id: &str) -> Option<&'static str> {\n");
    out.push_str("    match token_id {\n");
    for msg in &bundle.messages {
        write_match_some_arm(out, &msg.id, &msg.msg, "        ");
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    let known_ids: BTreeSet<&str> = bundle.messages.iter().map(|m| m.id.as_str()).collect();
    out.push_str("/// Looks up a translated static token for a non-English shipped locale.\n");
    out.push_str("#[must_use]\n");
    out.push_str(
        "pub fn translated_by_id(locale: Locale, token_id: &str) -> Option<&'static str> {\n",
    );
    out.push_str("    match locale {\n");
    for tr in &bundle.translations {
        if let Some(loc) = bundle.locales.iter().find(|l| l.tag == tr.locale_tag) {
            let _ = writeln!(
                out,
                "        Locale::{} => match token_id {{",
                loc.rust_variant
            );
            for (k, v) in tr
                .entries
                .iter()
                .filter(|(id, _)| known_ids.contains(id.as_str()))
            {
                write_match_some_arm(out, k, v, "            ");
            }
            out.push_str("            _ => None,\n        },\n");
        }
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    write_mf2_lookup_runtime(out, bundle);
}

fn display_width(text: &str) -> usize {
    text.chars()
        .map(|ch| {
            let cp = ch as u32;
            if (0x2E80..=0x9FFF).contains(&cp)
                || (0xF900..=0xFAFF).contains(&cp)
                || (0xFF01..=0xFF60).contains(&cp)
            {
                2
            } else {
                1
            }
        })
        .sum()
}

pub(crate) fn write_match_some_arm(out: &mut String, key: &str, val: &str, indent: &str) {
    let key_lit = rust_str(key);
    let val_lit = rust_str(val);
    let single = format!("{indent}{key_lit} => Some({val_lit}),");
    let block_inner = format!("{indent}    Some({val_lit})");
    if display_width(&single) <= 100 {
        let _ = writeln!(out, "{single}");
    } else if display_width(&block_inner) <= 100 {
        let _ = writeln!(out, "{indent}{key_lit} => {{");
        let _ = writeln!(out, "{block_inner}");
        let _ = writeln!(out, "{indent}}}");
    } else {
        let _ = writeln!(out, "{indent}{key_lit} => Some(");
        let _ = writeln!(out, "{indent}    {val_lit},");
        let _ = writeln!(out, "{indent}),");
    }
}

fn collect_rust_messages(bundle: &InterfaceBundle) -> Vec<&MessageSpec> {
    let mut out = Vec::new();
    for id in PREFERRED_RUST_MESSAGE_ORDER {
        if let Some(msg) = bundle
            .messages
            .iter()
            .find(|m| m.id == *id && m.rust_variant.is_some())
        {
            out.push(msg);
        }
    }
    for msg in &bundle.messages {
        if msg.rust_variant.is_some() && !PREFERRED_RUST_MESSAGE_ORDER.contains(&msg.id.as_str()) {
            out.push(msg);
        }
    }
    out
}
